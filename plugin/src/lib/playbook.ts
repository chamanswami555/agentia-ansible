// Renders a thin playbook that imports the collection's release window with the values read
// from Copado. Strings are emitted as JSON scalars, which YAML accepts, so no YAML library.

export interface ReleaseScaffold {
  storyIds: string[]
  /** Empty for story mode (Copado Submit per story); an 18-character id for promotion mode. */
  promotionId: string
  crtJobId?: string
  crtProjectId?: string
  repoDir: string
  evidenceRoot?: string
  approve?: boolean
  generatedAt: string
}

function scalar(value: string | boolean | number): string {
  return typeof value === 'string' ? JSON.stringify(value) : String(value)
}

function list(values: string[]): string {
  return `[${values.map((v) => JSON.stringify(v)).join(', ')}]`
}

export function renderReleasePlaybook(input: ReleaseScaffold): string {
  const title = `Release window for ${input.storyIds.join(', ')}`
  const lines = [
    '---',
    `# Generated by agentia ansible scaffold on ${input.generatedAt}.`,
    '# Review the values, then run: agentia ansible run --playbook <this file> [--check] [--approve]',
    `- name: ${scalar(title)}`,
    '  import_playbook: chamanswami555.agentia.release_window',
    '  vars:',
    `    story_ids: ${list(input.storyIds)}`,
    `    deploy_mode: ${scalar(input.promotionId ? 'promotion' : 'story')}`,
    `    promotion_id: ${scalar(input.promotionId)}`,
    `    crt_job_id: ${scalar(input.crtJobId ?? '')}`,
    `    crt_project_id: ${scalar(input.crtProjectId ?? '')}`,
    `    repo_dir: ${scalar(input.repoDir)}`,
  ]
  // a root, not a folder: every run of the generated playbook gets its own dated evidence folder
  if (input.evidenceRoot) lines.push(`    evidence_root: ${scalar(input.evidenceRoot)}`)
  lines.push(`    approve: ${scalar(Boolean(input.approve))}`)
  return `${lines.join('\n')}\n`
}

export function parseRecap(output: string): {ok: number; changed: number; failed: number; skipped: number} | undefined {
  const line = output.split('\n').find((l) => l.startsWith('localhost'))
  if (!line) return undefined
  const read = (key: string) => Number((line.match(new RegExp(`${key}=(\\d+)`)) ?? [])[1] ?? 0)
  return {ok: read('ok'), changed: read('changed'), failed: read('failed'), skipped: read('skipped')}
}
